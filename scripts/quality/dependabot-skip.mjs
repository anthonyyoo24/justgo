import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Dependabot cannot read Expo's version list, so it would bump packages the
// Expo SDK pins, or that ship native code, one at a time. Those move together
// in an Expo SDK upgrade instead (`npx expo install expo@<sdk> --fix`, a new
// development build and a device check). This script writes them into the
// `ignore` list of .github/dependabot.yml, and its test fails when the list
// drifts from the installed SDK.

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const mobile = join(root, 'apps/mobile');
const configPath = join(root, '.github/dependabot.yml');

export const begin =
  '      # BEGIN generated by scripts/quality/dependabot-skip.mjs. Run it with --write after an Expo upgrade.';
export const end = '      # END generated';

// Skipped for a reason outside Expo. Each entry says why.
export const otherSkips = [
  {
    name: 'wrangler',
    reason:
      'scripts/release/staging-worker-build.mjs accepts only the pinned Wrangler.',
  },
];

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function packageDir(name) {
  for (const base of [mobile, root]) {
    const dir = join(base, 'node_modules', name);
    if (existsSync(join(dir, 'package.json'))) return dir;
  }
  throw new Error(`${name} is not installed. Run npm ci first.`);
}

// A package ships native code when it has a podspec, an Expo module config,
// or a native folder.
export function shipsNativeCode(dir) {
  return readdirSync(dir).some(
    (entry) =>
      entry.endsWith('.podspec') ||
      entry === 'expo-module.config.json' ||
      entry === 'ios' ||
      entry === 'android',
  );
}

export function expoSkips() {
  const manifest = readJson(join(mobile, 'package.json'));
  const names = Object.keys({
    ...manifest.dependencies,
    ...manifest.devDependencies,
  }).filter((name) => !name.startsWith('@justgo/'));
  const pinned = readJson(
    join(packageDir('expo'), 'bundledNativeModules.json'),
  );
  return names
    .filter(
      (name) =>
        name === 'expo' ||
        Object.hasOwn(pinned, name) ||
        shipsNativeCode(packageDir(name)),
    )
    .sort();
}

const quote = (name) => (/^[\w-]+$/.test(name) ? name : `'${name}'`);

export function renderBlock(expo = expoSkips(), other = otherSkips) {
  const lines = [
    begin,
    '      # The Expo SDK pins these, or they ship native code. Upgrade them with the SDK.',
    ...expo.map((name) => `      - dependency-name: ${quote(name)}`),
  ];
  for (const { name, reason } of other)
    lines.push(`      # ${reason}`, `      - dependency-name: ${quote(name)}`);
  lines.push(end);
  return lines.join('\n');
}

export function currentBlock(config) {
  const start = config.indexOf(begin);
  const stop = config.indexOf(end);
  if (start < 0 || stop < start)
    throw new Error('dependabot.yml has no generated skip block.');
  return config.slice(start, stop + end.length);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const config = readFileSync(configPath, 'utf8');
  const expected = renderBlock();
  if (process.argv.includes('--write')) {
    writeFileSync(configPath, config.replace(currentBlock(config), expected));
    console.log('dependabot-skip: wrote .github/dependabot.yml');
  } else if (currentBlock(config) !== expected) {
    console.error(
      'dependabot-skip: .github/dependabot.yml is stale. Run node scripts/quality/dependabot-skip.mjs --write',
    );
    process.exitCode = 1;
  } else console.log('dependabot-skip: up to date');
}
